def translate(key: str, lang: str = 'zh-CN') -> str:
    """
    获取翻译文本
    
    Args:
        key: 翻译键
        lang: 语言代码 (zh-CN, zh-TW, en-US)
        
    Returns:
        翻译后的文本，如果找不到则返回键本身
    """
    # 验证语言
    if lang not in TRANSLATIONS:
        lang = 'zh-CN'  # fallback to Chinese
    
    # 获取翻译
    translation = TRANSLATIONS[lang].get(key)
    
    # 如果找不到，尝试fallback到中文
    if translation is None:
        translation = TRANSLATIONS['zh-CN'].get(key, key)
    
    return translation


def get_supported_languages() -> list:
    """获取支持的语言列表"""
    return list(TRANSLATIONS.keys())


